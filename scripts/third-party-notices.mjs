// Generates THIRD_PARTY_NOTICES: the licence of every package bundled into dist/, plus Tweego's.
//
// tsdown.config.ts calls updateThirdPartyNotices() after each build with the module IDs of the
// emitted JavaScript chunks, so the list comes from what the build actually bundled, not from a
// hand-kept list. The build fails when that set differs from `deps.onlyBundle`. CI rebuilds and
// fails when the committed THIRD_PARTY_NOTICES is out of date (`git diff --exit-code`).
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

export const NOTICES_FILE = 'THIRD_PARTY_NOTICES';

const NODE_MODULES = '/node_modules/';
const LICENCE_FILE = /^(?:licen[cs]e|copying)(?:[.-][\w.-]*)?$/i;
const RULE = '='.repeat(80);
const THIN_RULE = '-'.repeat(80);

