/**
 * The package name and root folder of a module ID inside node_modules, or undefined.
 * Handles pnpm's nested store paths, scoped packages and Windows separators.
 */
export function packageOfModuleId(moduleId) {
  if (moduleId.startsWith('\0')) return undefined;
  const slashed = moduleId.replaceAll('\\', '/');
  const at = slashed.lastIndexOf(NODE_MODULES);
  if (at === -1) return undefined;
  const rest = slashed.slice(at + NODE_MODULES.length).split('/');
  const [first, second] = rest;
  if (first === undefined || first === '' || first.startsWith('.')) return undefined;
  const name = first.startsWith('@') ? (second ? `${first}/${second}` : undefined) : first;
  if (name === undefined) return undefined;
  return { name, root: slashed.slice(0, at + NODE_MODULES.length + name.length) };
}

/** Every distinct package (name and root folder) that the given module IDs come from, sorted by name then root. */
export function bundledPackages(moduleIds) {
  const byRoot = new Map();
  for (const id of moduleIds) {
    const pkg = packageOfModuleId(id);
    if (pkg !== undefined) byRoot.set(pkg.root, pkg);
  }
  return [...byRoot.values()].sort((a, b) => compare(a.name, b.name) || compare(a.root, b.root));
}

/** The names in `bundled` that `allowed` lacks, and the names in `allowed` that nothing bundled. */
export function compareWithAllowList(bundled, allowed) {
  const names = new Set(bundled.map((p) => p.name));
  const allowedSet = new Set(allowed);
  return {
    unlisted: [...names].filter((n) => !allowedSet.has(n)).sort(compare),
    unused: [...allowedSet].filter((n) => !names.has(n)).sort(compare),
  };
}

/** Reads a bundled package's licence: SPDX id, project URL and the full licence text. */
export function readPackageLicence(pkg) {
  const context = `bundled package ${pkg.name} (${pkg.root})`;
  let manifest;
  try {
    manifest = JSON.parse(readFileSync(join(pkg.root, 'package.json'), 'utf8'));
  } catch (cause) {
    throw new Error(`Cannot read package.json of ${context}`, { cause });
  }
  const license = typeof manifest.license === 'string' ? manifest.license : undefined;
  if (license === undefined) throw new Error(`${context} declares no "license" in its package.json`);
  const files = readdirSync(pkg.root)
    .filter((f) => LICENCE_FILE.test(f))
    .sort(compare);
  if (files.length === 0) throw new Error(`${context} ships no LICENSE file, so its notice cannot be reproduced`);
  const text = files.map((f) => normalizeText(readFileSync(join(pkg.root, f), 'utf8'))).join('\n\n');
  return { name: pkg.name, url: projectUrl(manifest), license, text };
}

/** The full THIRD_PARTY_NOTICES text for the given licences (LF line endings, trailing newline). */
export function renderThirdPartyNotices(licences) {
  const seen = new Set();
  const unique = licences.filter((l) => {
    const key = `${l.name}\n${l.text}`;
    if (seen.has(key)) return false;
    seen.add(key);
    return true;
  });
  const sections = [TWEEGO, ...unique].map((l) =>
    [RULE, l.name, ...(l.url ? [l.url] : []), `License: ${l.license}`, THIN_RULE, '', l.text].join('\n'),
  );
  return `${[HEADER, ...sections].join('\n\n')}\n`;
}

/**
 * Regenerates `file` from the module IDs a build bundled. Throws when the bundled packages
 * differ from `allowed` (the tsdown `deps.onlyBundle` list). Returns whether the file changed.
 */
export function updateThirdPartyNotices({ moduleIds, allowed, file }) {
  const bundled = bundledPackages(moduleIds);
  const { unlisted, unused } = compareWithAllowList(bundled, allowed);
  if (unlisted.length > 0 || unused.length > 0) {
    throw new Error(
      [
        'The bundled packages do not match deps.onlyBundle in tsdown.config.ts.',
        ...(unlisted.length > 0 ? [`Bundled but not listed: ${unlisted.join(', ')}`] : []),
        ...(unused.length > 0 ? [`Listed but not bundled: ${unused.join(', ')}`] : []),
      ].join('\n'),
    );
  }
  const text = renderThirdPartyNotices(bundled.map(readPackageLicence));
  let current;
  try {
    current = normalizeText(readFileSync(file, 'utf8'));
  } catch {
    current = undefined;
  }
  if (current !== undefined && `${current}\n` === text) return false;
  writeFileSync(file, text, 'utf8');
  return true;
}

function projectUrl(manifest) {
  const repo = typeof manifest.repository === 'string' ? manifest.repository : manifest.repository?.url;
  if (typeof repo === 'string') {
    return repo
      .replace(/^git\+/, '')
      .replace(/^git:\/\//, 'https://')
      .replace(/^github:/, 'https://github.com/')
      .replace(/\.git$/, '');
  }
  return typeof manifest.homepage === 'string' ? manifest.homepage : undefined;
}

function normalizeText(text) {
  return text
    .replace(/^﻿/, '')
    .replace(/\r\n?/g, '\n')
    .split('\n')
    .map((line) => line.trimEnd())
    .join('\n')
    .trim();
}

function compare(a, b) {
  return a < b ? -1 : a > b ? 1 : 0;
}
